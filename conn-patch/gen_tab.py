#!/usr/bin/env python3
"""Write conn_patch_tab.h from the car's Connectivity (the copy pulled from the head unit).

Usage: python3 -I gen_tab.py <Connectivity> <libconn_carplay.so> > conn_patch_tab.h
Each patch keeps the whole function around it as a fingerprint: conn_patch writes only if every byte of it
matches (the patch site may hold the original or the new bytes).

The table holds head-unit code, so it is not in the repository: every builder makes it from copies pulled from their
own head unit (car/car-chip-test.sh conn-pull). A function is taken only if its bytes hash to KNOWN below (the
firmware the patches were worked out on); a patch whose function differs is left out of the table with a warning, so
conn_patch never learns an address that is wrong for that firmware. No patch left: exit 1.
"""
import hashlib, struct, sys

# SHA-256 of each patch's context (factory bytes) in NBTevo_N18032I: Connectivity as running on the owner's head unit
# on 2026-11-26 (with nbt-aa's change, 7524836 bytes) and its libconn_carplay.so
KNOWN = {
    "c1": "f6dc589b7512b859211ae9504d769e533f403c6f1afd45325e97c25314825110",
    "c2": "fad652c6fd2b46810360f5d52fa43e09dee5e6c10d8d06e936d3e5d841666ce9",
    "w1": "0de0d097f83cb18cfdb40a73ee8550d5547396940432546e376f5398fd1f9903",
}

PATCHES = [
    # name, what, module (None: Connectivity itself), context start, context end (exclusive), site, new bytes
    ("c1", "a session the iPhone started becomes ACTIVE (informationUpdateSessionStatus: no DipoState check)",
     None, 0x603e1c, 0x603ebc, 0x603e70, bytes.fromhex("0030a0e3")),
    ("c2", "a controller's id is stored as the phone's address instead of compared (updateControllerAdded)",
     None, 0x608cc4, 0x608d84, 0x608d4c, bytes.fromhex("0600a0e1" "0510a0e1" "91a8eceb")),
    # libconn_carplay.so CCarPlayServiceCore::handleSessionStart: `bne` past "adapter->setup(); startWLANDriver" for
    # every transport but WiFi / WFD -> nop: the factory iAP2 driver also starts for a wired session
    # (wired-carplay/iap2-factory-re-2026-11-27.md)
    ("w1", "the factory iAP2 driver starts for a wired session too (handleSessionStart: no WiFi/WFD check)",
     "libconn_carplay.so", 0x293ac, 0x294e0, 0x294a8, bytes.fromhex("0000a0e1")),
]

def load_map(d):
    assert d[:4] == b"\x7fELF" and d[4] == 1 and d[5] == 1, "not a 32-bit little-endian ELF"
    phoff, = struct.unpack_from("<I", d, 0x1c)
    phentsize, phnum = struct.unpack_from("<HH", d, 0x2a)
    segs = []
    for i in range(phnum):
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from("<5I", d, phoff + i * phentsize)
        if p_type == 1:
            segs.append((p_vaddr, p_offset, p_filesz))
    return segs

def read_va(d, segs, va, n):
    for v, o, sz in segs:
        if v <= va and va + n <= v + sz:
            return d[o + va - v:o + va - v + n]
    raise SystemExit("0x%x not in a LOAD segment" % va)

def c_bytes(b):
    rows = []
    for i in range(0, len(b), 16):
        rows.append("    " + " ".join("0x%02x," % x for x in b[i:i + 16]))
    return "\n".join(rows)

def selftest(path, addr, lib, addr2):
    """the table for selftest/patch_target (t1: answer()) and selftest/libpt.so (t2: answer2(), a library patch):
    "mov r0, #1" becomes "mov r0, #2" """
    new = bytes.fromhex("0200a0e3")
    print("/* Generated by gen_tab.py --selftest from out/patch_target and out/libpt.so. */")
    rows = []
    for name, f, a, module in (("t1", path, int(addr, 16), None), ("t2", lib, int(addr2, 16), "libpt.so")):
        d = open(f, "rb").read()
        ctx = read_va(d, load_map(d), a, 8)
        assert ctx[:4] == bytes.fromhex("0100a0e3"), name + ": does not start with mov r0, #1: " + ctx.hex()
        print("static const unsigned char ctx_%s[8] = {\n%s\n};" % (name, c_bytes(ctx)))
        print("static const unsigned char new_%s[4] = {\n%s\n};" % (name, c_bytes(new)))
        rows.append('    {"%s", "%s returns 2 instead of 1", 0x%xu, 8, ctx_%s, 0x%xu, 4, new_%s, %s},'
                    % (name, "answer()" if name == "t1" else "answer2() in libpt.so", a, name, a, name,
                       '"%s"' % module if module else "0"))
    print("static const struct patch g_patches[] = {")
    print("\n".join(rows))
    print("};")

def main():
    if sys.argv[1] == "--selftest":
        return selftest(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5])
    files = {None: open(sys.argv[1], "rb").read(), "libconn_carplay.so": open(sys.argv[2], "rb").read()}
    out = ["/* Generated by gen_tab.py from the car's /opt/conn/bin/Connectivity and",
           " * /opt/conn/lib/carplay/devctrl/libconn_carplay.so (NBTevo_N18032I, as running on 2026-11-26).",
           " * Do not edit by hand. */", ""]
    taken = []
    for name, what, module, a, b, site, new in PATCHES:
        d = files[module]
        try:
            ctx = read_va(d, load_map(d), a, b - a)
        except SystemExit:
            ctx = b""
        if hashlib.sha256(ctx).hexdigest() != KNOWN[name]:
            sys.stderr.write("gen_tab: %s left out: its function in %s is not the one it was made for "
                             "(other firmware)\n" % (name, module or "Connectivity"))
            continue
        assert a <= site and site + len(new) <= b
        assert ctx[site - a:site - a + len(new)] != new, name + ": the copy is already patched"
        taken.append((name, what, module, a, b, site, new))
        out.append("static const unsigned char ctx_%s[%d] = {\n%s\n};" % (name, len(ctx), c_bytes(ctx)))
        out.append("static const unsigned char new_%s[%d] = {\n%s\n};" % (name, len(new), c_bytes(new)))
    if not taken:
        raise SystemExit("gen_tab: no patch fits these files: conn_patch cannot be built for this head unit")
    out.append("")
    out.append("static const struct patch g_patches[] = {")
    for name, what, module, a, b, site, new in taken:
        out.append('    {"%s", "%s", 0x%xu, sizeof(ctx_%s), ctx_%s, 0x%xu, sizeof(new_%s), new_%s, %s},'
                   % (name, what, a, name, name, site, name, name, '"%s"' % module if module else "0"))
    out.append("};")
    print("\n".join(out))

main()
